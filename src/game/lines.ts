/** 场景内轮换抽取（不连续重复） */
export class LineBag {
  private last: Record<string, number> = {};

  constructor(private lines: ArchetypeLines) {}

  scene(scene: TalkScene): string {
    const pool = this.lines[scene] ?? this.lines.dive;
    return this.pick(scene, pool);
  }

  talk(type: TalkEventType): string {
    return this.lines.talk[type] ?? '……账本这一页，字迹未干。';
  }

  private pick(key: string, pool: string[]): string {
    if (pool.length === 0) return '……';
    let i = Math.floor(Math.random() * pool.length);
    if (pool.length > 1 && i === this.last[key]) i = (i + 1) % pool.length;
    this.last[key] = i;
    return pool[i]!;
  }
}
