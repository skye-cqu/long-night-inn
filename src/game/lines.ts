import type { Archetype } from './config';

export type TalkScene =
  | 'opening' // 下潜开场
  | 'dive' // 下潜途中间歇碎碎念
  | 'pickup' // 拾取战利品
  | 'fear' // 实体逼近（恐惧表生效）
  | 'caught' // 被抓拖回门口
  | 'doorclose' // 倒计时归零门关
  | 'settle' // 归航结算（账单卡吐槽也从这里抽）
  | 'speak' // 玩家按 T 说话后的回应
  | 'whisper' // 低语雷达（含 {dir}）
  | 'survivor' // 靠近幸存者槽位时的低语提示（E2 遭遇）
  | 'saved' // 选「救」：旅人开始跟随（E2）
  | 'rob' // 选「抢」：伙计震惊（E2）
  | 'lost'; // 旅人失踪（跟随途中玩家被抓 / 门关，E2）

/** 夜谈：对本夜第一条账本记录的评论（按事件类型选池） */
export type TalkEventType =
  | 'loot'
  | 'caught'
  | 'noise_speak'
  | 'door_close'
  | 'unpaid'
  | 'paid'
  | 'return'
  | 'survivor_saved'
  | 'survivor_ignored'
  | 'survivor_robbed'
  | 'survivor_lost';

export interface ArchetypeLines {
  opening: string[];
  dive: string[];
  pickup: string[];
  fear: string[];
  caught: string[];
  doorclose: string[];
  settle: string[];
  speak: string[];
  whisper: string[];
  /** 幸存者遭遇（E2）：低语提示 / 救下 / 抢夺震惊 / 失踪 */
  survivor: string[];
  saved: string[];
  rob: string[];
  lost: string[];
  /** 夜谈：按账本事件类型的评语（伙计的记忆机制；每型 ≥1 条，幸存者四型 ≥2 条） */
  talk: Record<TalkEventType, string[]>;
}

